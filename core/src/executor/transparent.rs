use std::sync::{Arc, Mutex};
use std::time::Instant;

use aicore_contracts::{
    control::{
        rollback::RollbackRecord,
        stage::{ControlStage, StageOutcome},
        trace::ControlTrace,
    },
    execution::{status::ExecutionOverallStatus, targets::ExecutionTargets},
    policy::resource_policy::ResourcePolicy,
    traits::{
        policy_executor::{IPolicyExecutor, IPolicyTransaction},
        post_condition_checker::{IPostConditionChecker, PostConditionResult},
        transparent_executor::ITransparentExecutor,
    },
};

/// Execute, independently verify and restore adapter-owned original snapshots.
/// Prior policies remain advisory history and cannot prove resource restoration.
pub struct TransparentExecutor {
    inner: Arc<dyn IPolicyExecutor>,
    checker: Option<Arc<dyn IPostConditionChecker>>,
    last_result: Mutex<Option<aicore_contracts::execution::result::ExecutionResult>>,
}

impl TransparentExecutor {
    pub fn new(inner: Arc<dyn IPolicyExecutor>) -> Self {
        Self {
            inner,
            checker: None,
            last_result: Mutex::new(None),
        }
    }

    pub fn with_checker(mut self, checker: Arc<dyn IPostConditionChecker>) -> Self {
        self.checker = Some(checker);
        self
    }

    pub fn has_checker(&self) -> bool {
        self.checker.is_some()
    }
}

impl ITransparentExecutor for TransparentExecutor {
    fn execute_transparent(
        &self,
        policy: &ResourcePolicy,
        targets: &ExecutionTargets,
        _prior_policy: Option<&ResourcePolicy>,
    ) -> ControlTrace {
        let trace_start = Instant::now();
        let trace_id = format!("control-{}", policy.policy_id);

        let mut stages: Vec<StageOutcome> = Vec::with_capacity(6);

        // 1. Observe: V3-E is considered to have been completed by AdaptiveLoop; only skipping is recorded.
        stages.push(StageOutcome::skipped(
            ControlStage::Observe,
            "observation handled by AdaptiveLoop",
        ));

        // 2. Decide: policy has been generated by PolicyEngine; records skip.
        stages.push(StageOutcome::skipped(
            ControlStage::Decide,
            format!("policy prepared: source={:?}", policy.source),
        ));

        // 3. Validate: Pass through Validator before entering this implementer; record skipping.
        stages.push(StageOutcome::skipped(
            ControlStage::Validate,
            "policy validated before execution",
        ));

        // 4. Apply
        let apply_start = Instant::now();
        let mut transaction = match self.inner.begin_transaction(policy, targets) {
            Ok(transaction) => transaction,
            Err(error) => {
                let result = super::policy_executor::capture_failed(policy, error);
                if let Ok(mut slot) = self.last_result.lock() {
                    *slot = Some(result.clone());
                }
                stages.push(StageOutcome::failed(
                    ControlStage::Apply,
                    0,
                    "original-state capture failed; no writes attempted",
                ));
                stages.push(StageOutcome::skipped(
                    ControlStage::Verify,
                    "no writes attempted",
                ));
                stages.push(StageOutcome::skipped(
                    ControlStage::Rollback,
                    "no writes attempted",
                ));
                return ControlTrace {
                    trace_id,
                    policy_id: policy.policy_id.clone(),
                    stages,
                    final_status: result.overall_status,
                    rollback: RollbackRecord::not_triggered(),
                    total_duration_ms: trace_start.elapsed().as_millis() as u64,
                };
            },
        };
        let apply_result = match transaction.as_mut() {
            Some(transaction) => transaction.apply(),
            None => self.inner.execute(policy, targets),
        };
        let apply_duration = apply_start.elapsed().as_millis() as u64;
        let apply_status = apply_result.overall_status;
        if let Ok(mut slot) = self.last_result.lock() {
            *slot = Some(apply_result.clone());
        }

        stages.push(match apply_status {
            ExecutionOverallStatus::AllSucceeded | ExecutionOverallStatus::PartiallySucceeded => {
                StageOutcome::success(
                    ControlStage::Apply,
                    apply_duration,
                    format!("overall={:?}", apply_status),
                )
            },
            ExecutionOverallStatus::NoOp => {
                StageOutcome::skipped(ControlStage::Apply, format!("overall={:?}", apply_status))
            },
            ExecutionOverallStatus::AllFailed => StageOutcome::failed(
                ControlStage::Apply,
                apply_duration,
                format!("overall={:?}", apply_status),
            ),
        });

        // 5. Verify
        let verify_start = Instant::now();
        let verify_outcome = self.run_verify(policy, &apply_result, &apply_status);
        let verify_duration = verify_start.elapsed().as_millis() as u64;

        let mut should_rollback = false;
        let mut rollback_reason = String::new();

        match verify_outcome {
            PostConditionResult::Passed => {
                stages.push(StageOutcome::success(
                    ControlStage::Verify,
                    verify_duration,
                    "post-condition passed",
                ));
            },
            PostConditionResult::NotApplicable => {
                stages.push(StageOutcome::skipped(
                    ControlStage::Verify,
                    "post-condition not applicable",
                ));
            },
            PostConditionResult::Failed(reason) => {
                should_rollback = true;
                rollback_reason = format!("verify failed: {}", reason);
                stages.push(StageOutcome::failed(
                    ControlStage::Verify,
                    verify_duration,
                    &rollback_reason,
                ));
            },
        }

        // Apply triggers a retreat when it fails.
        if apply_status == ExecutionOverallStatus::AllFailed
            || apply_result
                .outcomes
                .iter()
                .any(|o| o.status.is_real_failure())
        {
            should_rollback = true;
            rollback_reason = "apply contained failed resource operations".to_string();
        }

        // 6. Rollback
        let rollback = if should_rollback {
            self.do_rollback(policy, &mut transaction, &rollback_reason, &mut stages)
        } else {
            let rec = RollbackRecord::not_triggered();
            stages.push(StageOutcome::skipped(
                ControlStage::Rollback,
                "no rollback needed",
            ));
            rec
        };

        let total_duration_ms = trace_start.elapsed().as_millis() as u64;

        let final_status = if rollback.triggered {
            // Recovery describes the original state, not success of the request.
            ExecutionOverallStatus::AllFailed
        } else {
            apply_status
        };

        ControlTrace {
            trace_id,
            policy_id: policy.policy_id.clone(),
            stages,
            final_status,
            rollback,
            total_duration_ms,
        }
    }

    fn last_execution_result(
        &self,
    ) -> Option<aicore_contracts::execution::result::ExecutionResult> {
        self.last_result.lock().ok().and_then(|slot| slot.clone())
    }

    fn name(&self) -> &'static str {
        "transparent_executor"
    }
}

impl TransparentExecutor {
    fn run_verify(
        &self,
        policy: &ResourcePolicy,
        result: &aicore_contracts::execution::result::ExecutionResult,
        apply_status: &ExecutionOverallStatus,
    ) -> PostConditionResult {
        // Apply Failed
        if *apply_status == ExecutionOverallStatus::AllFailed {
            return PostConditionResult::Failed("apply returned AllFailed".to_string());
        }

        // NoOp (lack of capacity) Not applicable
        if *apply_status == ExecutionOverallStatus::NoOp {
            return PostConditionResult::NotApplicable;
        }

        // Call from checker
        if let Some(checker) = &self.checker {
            return checker.verify(policy, result);
        }

        // Apply's return value cannot be considered a validated system state without readback capability.
        PostConditionResult::NotApplicable
    }

    fn do_rollback(
        &self,
        policy: &ResourcePolicy,
        transaction: &mut Option<Box<dyn IPolicyTransaction + '_>>,
        reason: &str,
        stages: &mut Vec<StageOutcome>,
    ) -> RollbackRecord {
        let start = Instant::now();

        let transaction = match transaction {
            Some(transaction) => transaction,
            None => {
                let duration_ms = start.elapsed().as_millis() as u64;
                stages.push(StageOutcome::failed(
                    ControlStage::Rollback,
                    duration_ms,
                    "executor supplied no original-state snapshot; prior policy replay cannot prove restoration",
                ));
                return RollbackRecord::triggered(
                    Some(policy.policy_id.clone()),
                    None,
                    reason,
                    false,
                );
            },
        };

        let outcomes = transaction.restore();
        let duration_ms = start.elapsed().as_millis() as u64;

        let succeeded = !outcomes.is_empty()
            && outcomes
                .iter()
                .all(|o| o.status == aicore_contracts::execution::status::ExecutionStatus::Success);

        let detail = format!("original-state restoration: {:?}", outcomes);

        if succeeded {
            stages.push(StageOutcome::success(
                ControlStage::Rollback,
                duration_ms,
                detail,
            ));
        } else {
            stages.push(StageOutcome::failed(
                ControlStage::Rollback,
                duration_ms,
                detail,
            ));
        }

        RollbackRecord::triggered(Some(policy.policy_id.clone()), None, reason, succeeded)
    }
}
